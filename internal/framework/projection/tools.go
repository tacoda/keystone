package projection

import (
	"fmt"
	"path"
	"strconv"
	"strings"

	"github.com/tacoda/keystone/internal/framework/primitive"
)

// pluginToolDest places a `transport: plugin` tool as a native host tool;
// other transports have no host file ("" means none).
func pluginToolDest(dir, ext string) func(primitive.Primitive) string {
	return func(p primitive.Primitive) string {
		if p.Transport != "plugin" {
			return ""
		}
		return path.Join(dir, primitive.ProjectedName(p.ID)+ext)
	}
}

// opencodeTool renders an opencode custom tool (.opencode/tools/<id>.ts)
// that runs the charter tool through `keystone tool run`, so the handler
// and its argument checks stay in one place. Strings are quoted with
// strconv.Quote, which yields valid JavaScript string literals.
func opencodeTool(p primitive.Primitive, _ string) ([]byte, error) {
	var b strings.Builder
	fmt.Fprintf(&b, "// Generated by keystone project from %s. Edit the source, not this file.\n", p.Path)
	b.WriteString("import { tool } from \"@opencode-ai/plugin\"\n\nexport default tool({\n")
	fmt.Fprintf(&b, "  description: %s,\n  args: {\n", strconv.Quote(p.Description))
	for _, a := range p.Args {
		fmt.Fprintf(&b, "    %s: tool.schema.string()%s.describe(%s),\n", strconv.Quote(a.Name), optional(a), strconv.Quote(a.Description))
	}
	b.WriteString("  },\n  async execute(args, context) {\n")
	b.WriteString("    const argv: string[] = []\n")
	b.WriteString("    for (const [name, value] of Object.entries(args)) {\n")
	b.WriteString("      if (value !== undefined) argv.push(\"--\" + name, String(value))\n    }\n")
	fmt.Fprintf(&b, "    return await Bun.$`keystone tool run ${%s} ${argv}`.cwd(context.worktree).text()\n", strconv.Quote(p.ID))
	b.WriteString("  },\n})\n")
	return []byte(b.String()), nil
}

func optional(a primitive.Arg) string {
	if a.Required {
		return ""
	}
	return ".optional()"
}
