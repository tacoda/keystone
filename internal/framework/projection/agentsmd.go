// Managed-block markers. Keystone owns only the text between them, so a
// root file the user also edits (AGENTS.md, CLAUDE.md) is never overwritten.
const (
	BlockStart = "<!-- keystone:start -->"
	BlockEnd   = "<!-- keystone:end -->"
)

// MergeBlock returns existing with block placed between the markers:
// replaced in place when the markers exist, otherwise inserted after the
// first H1 (or at the top) with all other content kept. Pure; no I/O.
func MergeBlock(existing, block string) string {
	bracketed := BlockStart + "\n" + strings.TrimSpace(block) + "\n" + BlockEnd
	if start, end := strings.Index(existing, BlockStart), strings.Index(existing, BlockEnd); start >= 0 && end > start {
		return existing[:start] + bracketed + existing[end+len(BlockEnd):]
	}
	lines := strings.Split(existing, "\n")
	at := 0
	for i, line := range lines {
		if strings.HasPrefix(line, "# ") {
			at = i + 1
			break
		}
	}
	before := strings.TrimRight(strings.Join(lines[:at], "\n"), "\n")
	after := strings.Trim(strings.Join(lines[at:], "\n"), "\n")
	return joinNonEmpty(before, bracketed, after) + "\n"
}

func joinNonEmpty(parts ...string) string {
	var keep []string
	for _, p := range parts {
		if p != "" {
			keep = append(keep, p)
		}
	}
	return strings.Join(keep, "\n\n")
}

// RootOutputs plans the root entrypoint files: the AGENTS.md block (every
// project; it is the cross-tool standard), the CLAUDE.md block importing it
// (Claude Code reads AGENTS.md only when no CLAUDE.md exists), and Aider's
// read list.
func RootOutputs(primitives []primitive.Primitive, hosts []Profile) []Output {
	outs := []Output{{Host: "agents-md", Dest: "AGENTS.md", Strategy: Block, Content: []byte(AgentsMD(primitives, hosts))}}
	for _, h := range hosts {
		switch h.Host {
		case "claude-code":
			outs = append(outs, Output{Host: h.Host, Dest: "CLAUDE.md", Strategy: Block, Content: []byte(claudeBlock)})
		case "aider":
			outs = append(outs, Output{Host: h.Host, Dest: ".aider.conf.yml", Strategy: Shim, Content: []byte(aiderConf)})
		}
	}
	return outs
}

