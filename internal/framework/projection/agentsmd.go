// AgentsMD renders the AGENTS.md managed block: the whole orientation, in
// one place, for every host that reads AGENTS.md.
func AgentsMD(primitives []primitive.Primitive, hosts []Profile) string {
	var b strings.Builder
	b.WriteString(agentsIntro)
	writeKindSection(&b, "Constraints", primitive.CategoryConstraint)
	writeKindSection(&b, "Capabilities", primitive.CategoryCapability)
	writeEverywhereRules(&b, primitives)
	b.WriteString(agentsLaws)
	writeHosts(&b, primitives, hosts)
	return b.String()
}

func writeKindSection(b *strings.Builder, title string, cat primitive.Category) {
	fmt.Fprintf(b, "\n## %s\n\n", title)
	for _, k := range kindDirs {
		if primitive.CategoryOf(k.kind) == cat {
			fmt.Fprintf(b, "- **%s** (`.agents/%s/`) — %s.\n", k.kind, k.dir, k.what)
		}
	}
}

// writeEverywhereRules lists rules without paths: — they apply to every
// task, but stay one line each here; the body is opened on demand.
func writeEverywhereRules(b *strings.Builder, primitives []primitive.Primitive) {
	var lines []string
	for _, p := range primitives {
		if appliesEverywhere(p) {
			lines = append(lines, fmt.Sprintf("- `%s` — %s", p.Path, strings.TrimSpace(p.Description)))
		}
	}
	if len(lines) == 0 {
		return
	}
	sort.Strings(lines)
	b.WriteString("\n## Rules that apply everywhere\n\nOpen the one that fits the phase you are in.\n\n")
	b.WriteString(strings.Join(lines, "\n") + "\n")
}

// appliesEverywhere is an inferential rule with no paths: scope.
func appliesEverywhere(p primitive.Primitive) bool {
	if primitive.Kind(p.Kind) != primitive.KindRule || p.Mode == "computational" {
		return false
	}
	return len(p.Paths) == 0
}

// writeHosts states, per enabled host, what it loads by itself and what
// the agent must open from .agents/ by hand.
func writeHosts(b *strings.Builder, primitives []primitive.Primitive, hosts []Profile) {
	b.WriteString("\n## On each host\n\n")
	hooksOnHostEvents := len(claudecode.HostPhases(primitives)) > 0
	rules := CollectRules(primitives)
	for _, h := range hosts {
		line := hostLine(h)
		if hooksOnHostEvents && h.Hooks == nil {
			line += "; does **not** run hooks — " + ReportAdvice(string(primitive.KindHook))
		}
		if n := unenforcedRules(h, rules); n > 0 {
			line += fmt.Sprintf("; does **not** enforce %d permission rule(s) — %s", n, ReportAdvice(string(primitive.KindPermission)))
		}
		b.WriteString(line + ".\n")
	}
}

// unenforcedRules counts the charter's permission rules host h cannot express.
func unenforcedRules(h Profile, r Rules) int {
	if r.empty() {
		return 0
	}
	if h.Permissions == nil {
		return len(allRules(r))
	}
	_, unsupported := h.Permissions(r, nil)
	return len(unsupported)
}

// ReportAdvice is what the agent must do itself when a host cannot enforce
// a constraint kind.
func ReportAdvice(kind string) string {
	switch primitive.Kind(kind) {
	case primitive.KindHook:
		return "run the checks in `.agents/hooks/` yourself before claiming done"
	case primitive.KindPermission:
		return "follow the deny / ask lists in `.agents/permissions/` yourself"
	}
	return "apply it yourself"
}

// hostLine is one host's bullet: what it loads by itself, and what the
// agent must open from .agents/ by hand.
func hostLine(h Profile) string {
	auto, manual := hostKinds(h)
	var parts []string
	if len(auto) > 0 {
		parts = append(parts, "loads "+strings.Join(auto, ", ")+" by itself")
	}
	if len(manual) > 0 {
		parts = append(parts, "open "+strings.Join(manual, ", ")+" from `.agents/` yourself")
	}
	line := "- **" + hostNames[h.Host] + "**"
	if len(parts) > 0 {
		line += " — " + strings.Join(parts, "; ")
	}
	return line
}

func hostKinds(h Profile) (auto, manual []string) {
	for _, k := range kindDirs {
		r, ok := h.Rules[k.kind]
		switch {
		case !ok:
		case r.Strategy == Index:
			manual = append(manual, plural(k.kind))
		default:
			auto = append(auto, plural(k.kind))
		}
	}
	return auto, manual
}

func plural(k primitive.Kind) string {
	if k == primitive.KindHook {
		return "hooks (inferential)"
	}
	return string(k) + "s"
}

