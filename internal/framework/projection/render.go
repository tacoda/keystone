package projection

import (
	"path"
	"strings"

	"gopkg.in/yaml.v3"

	"github.com/tacoda/keystone/internal/framework/primitive"
)

// withFrontmatter renders v as YAML frontmatter above body.
func withFrontmatter(v any, body string) ([]byte, error) {
	var b strings.Builder
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(v); err != nil {
		return nil, err
	}
	if err := enc.Close(); err != nil {
		return nil, err
	}
	return []byte("---\n" + b.String() + "---\n\n" + strings.TrimLeft(body, "\n")), nil
}

// ruleRenderer renders a rule shim: host frontmatter from fm(p) above the
// shared rule body (title, pointer to the full rule, high-signal sections).
func ruleRenderer(fm func(primitive.Primitive) any) Renderer {
	return func(p primitive.Primitive, contents string) ([]byte, error) {
		return withFrontmatter(fm(p), primitive.RuleShimMarkdown(contents, p))
	}
}

// bodyRenderer renders host frontmatter from fm(p) above the primitive's
// own markdown body (commands, subagents).
func bodyRenderer(fm func(primitive.Primitive) any) Renderer {
	return func(p primitive.Primitive, contents string) ([]byte, error) {
		return withFrontmatter(fm(p), primitive.Body(contents))
	}
}

// pathRuleDest projects only path-scoped inferential rules; always-on
// rules live in AGENTS.md, and computational rules fire as hooks.
func pathRuleDest(dir, ext string) func(primitive.Primitive) string {
	return func(p primitive.Primitive) string {
		if p.Mode == "computational" || len(p.Paths) == 0 {
			return ""
		}
		return path.Join(dir, primitive.RuleSlug(p.ID)+ext)
	}
}

// nameDest projects under the shared keystone-prefixed name.
func nameDest(dir, suffix string) func(primitive.Primitive) string {
	return func(p primitive.Primitive) string {
		return path.Join(dir, primitive.ProjectedName(p.ID)+suffix)
	}
}

// skillDirDest mirrors a whole skill directory under its canonical name.
// Flat 4.x skill files have no directory and are skipped.
func skillDirDest(dir string) func(primitive.Primitive) string {
	return func(p primitive.Primitive) string {
		if path.Base(p.Path) != "SKILL.md" {
			return ""
		}
		return path.Join(dir, path.Base(skillDir(p)))
	}
}

// argumentHint renders a command's args as `<a> <b>`.
func argumentHint(args []primitive.Arg) string {
	parts := make([]string, len(args))
	for i, a := range args {
		parts[i] = "<" + a.Name + ">"
	}
	return strings.Join(parts, " ")
}

// tomlString renders s as a TOML basic string.
func tomlString(s string) string {
	r := strings.NewReplacer(`\`, `\\`, `"`, `\"`, "\n", `\n`, "\r", `\r`, "\t", `\t`)
	return `"` + r.Replace(s) + `"`
}

// codexAgent renders a Codex subagent: TOML with the body as
// developer_instructions (required by Codex).
func codexAgent(p primitive.Primitive, contents string) ([]byte, error) {
	var b strings.Builder
	b.WriteString("# Generated by keystone project from " + p.Path + " — edit the source.\n")
	b.WriteString("name = " + tomlString(primitive.ProjectedName(p.ID)) + "\n")
	b.WriteString("description = " + tomlString(p.Description) + "\n")
	if p.Model != "" {
		b.WriteString("model = " + tomlString(p.Model) + "\n")
	}
	b.WriteString("developer_instructions = " + tomlString(strings.TrimSpace(primitive.Body(contents))) + "\n")
	return []byte(b.String()), nil
}
